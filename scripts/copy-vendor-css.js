#!/usr/bin/env node
/**
 * Builds the on-demand vendor CSS bundles.
 *
 * Two stylesheets used to sit in angular.json's global `styles` array, which
 * made them render-blocking on every page:
 *
 *   - Angular Material's prebuilt theme (~110KB) — but the only Material
 *     component on any public page is <mat-icon>, which needs no theme at
 *     all (its font is already self-hosted). Everything the theme actually
 *     styles (form fields, chips, expansion panels) lives under
 *     features/admin.
 *   - Prism's theme + plugin CSS — needed only on blog/:slug.
 *
 * Both are now emitted here as plain assets under public/assets/themes/ and
 * pulled in at runtime by the routes that need them (see load-stylesheet.ts).
 *
 * Filenames carry a content hash because .htaccess serves everything under
 * /assets with `Cache-Control: immutable` — a stable name would pin the old
 * bytes in browser caches forever across an Angular Material upgrade. The
 * hashed names are written to a generated TS module so the app imports them
 * as typed constants rather than hardcoding a path that would silently go
 * stale.
 *
 * Runs from the frontend `prebuild` script, i.e. before every `ng build`.
 * The generated file is committed so `ng serve` works without a prebuild.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const NODE_MODULES = path.join(ROOT, 'frontend/node_modules');
const OUT_DIR = path.join(ROOT, 'frontend/public/assets/themes');
const GENERATED_TS = path.join(
  ROOT,
  'frontend/src/app/core/utils/vendor-css.generated.ts',
);

/** Output bundle name → source files, concatenated in order. */
const BUNDLES = {
  material: [
    '@angular/material/prebuilt-themes/indigo-pink.css',
  ],
  prism: [
    'prismjs/themes/prism-tomorrow.css',
    'prismjs/plugins/line-numbers/prism-line-numbers.css',
    'prismjs/plugins/toolbar/prism-toolbar.css',
  ],
};

function build() {
  fs.mkdirSync(OUT_DIR, { recursive: true });

  // Drop previously generated bundles so stale hashes don't accumulate in
  // public/ and get deployed forever.
  for (const stale of fs.readdirSync(OUT_DIR)) {
    if (/^(material|prism)-[a-f0-9]{8}\.css$/.test(stale)) {
      fs.unlinkSync(path.join(OUT_DIR, stale));
    }
  }

  const emitted = {};

  for (const [name, sources] of Object.entries(BUNDLES)) {
    const css = sources
      .map((rel) => {
        const abs = path.join(NODE_MODULES, rel);
        if (!fs.existsSync(abs)) {
          throw new Error(
            `[vendor-css] Missing source: ${rel}\n` +
              `Run "npm install" in frontend/ before building.`,
          );
        }
        return `/* ${rel} */\n${fs.readFileSync(abs, 'utf8')}`;
      })
      .join('\n');

    const hash = crypto
      .createHash('sha256')
      .update(css)
      .digest('hex')
      .slice(0, 8);
    const filename = `${name}-${hash}.css`;

    fs.writeFileSync(path.join(OUT_DIR, filename), css);
    emitted[name] = `/assets/themes/${filename}`;

    console.log(
      `[vendor-css] ${filename} — ${(css.length / 1024).toFixed(1)} KB`,
    );
  }

  const banner = `// GENERATED by scripts/copy-vendor-css.js — do not edit by hand.
// Regenerated on every build; committed so \`ng serve\` works without a prebuild.
`;
  const body = Object.entries(emitted)
    .map(
      ([name, href]) =>
        `export const ${name.toUpperCase()}_CSS = '${href}';`,
    )
    .join('\n');

  fs.mkdirSync(path.dirname(GENERATED_TS), { recursive: true });
  fs.writeFileSync(GENERATED_TS, `${banner}\n${body}\n`);
  console.log(`[vendor-css] wrote ${path.relative(ROOT, GENERATED_TS)}`);
}

build();
